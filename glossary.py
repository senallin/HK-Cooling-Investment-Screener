"""Plain-language explanations of the financial and engineering terms used in the app. One source of wording:
the ⓘ buttons next to results and the full glossary on the Data and assumptions tab both read from TERMS.
Each entry: (term, what it is, why it matters here)."""

TERMS = {
    "capex": ("Investment (capex)",
              "Money spent up front to buy or build equipment: chillers, a central plant, pipes, connection works.",
              "Options with a big investment now can still win if they cost less to run every year afterwards."),
    "opex": ("Running cost (opex)",
             "What it costs every year to operate: electricity, maintenance and, for district cooling, the monthly charges.",
             "Year-1 running cost shows the yearly difference between options before any discounting."),
    "cashflow": ("Cash flow",
                 "The money going out (or saved) in each year of the analysis period, year 0 being the investment year.",
                 "Every result in the app is built from these yearly cash flows; you can download them under 'Detailed table'."),
    "discount": ("Discount rate",
                 "How much less a dollar received in the future is worth than a dollar today, in % per year (here in 'real' terms, i.e. after inflation).",
                 "A higher rate makes future savings count for less, which favours options that cost less now."),
    "pv": ("Present value (PV)",
           "Future cash flows converted into today's money using the discount rate, then added up.",
           "It lets an option that is cheap now but expensive later be compared fairly with one that is the opposite."),
    "lifecycle": ("Lifecycle cost",
                  "The present value of everything an option costs over the whole analysis period: investment, replacements, electricity, maintenance and charges.",
                  "The option with the lowest lifecycle cost is the cheapest way to provide the same cooling over time."),
    "npv": ("NPV saving",
            "Net present value saving = lifecycle cost of keeping individual plants minus the lifecycle cost of the option.",
            "Positive means the option is cheaper over its life than keeping each building's own chillers; negative means it costs more."),
    "payback": ("Simple payback",
                "Years until the extra investment is earned back by the yearly saving, ignoring the time value of money.",
                "Quick to understand, but it flatters long projects because it treats a dollar in year 15 like a dollar today."),
    "discounted_payback": ("Discounted payback",
                           "Years until the cumulative discounted saving turns positive.",
                           "Stricter than simple payback; 'not within period' means the option never pays back in the years analysed."),
    "residual": ("Residual value",
                 "The remaining worth of equipment that still has life left at the end of the analysis period (straight-line).",
                 "Without it, an option that just bought new equipment in the last year would look unfairly expensive."),
    "levelised": ("Levelised cost of cooling",
                  "Lifecycle cost divided by the discounted amount of cooling delivered, in HK$ per kWh of cooling.",
                  "A price per unit of cooling, so clusters of different sizes can be compared."),
    "emissions": ("Emissions (tCO₂e)",
                  "Tonnes of CO₂-equivalent per year from the electricity each option uses, at the grid emission factor.",
                  "For district cooling, the central plant's electricity is included (attributed) so the comparison is fair."),
    "cop": ("COP (coefficient of performance)",
            "Units of cooling delivered per unit of electricity used. A COP of 5 means 5 kWh of cooling for 1 kWh of electricity.",
            "Higher is better: efficiency is the main reason a shared or district plant can use less electricity."),
    "diversity": ("Peak diversity",
                  "Buildings rarely all hit their peak at the same moment, so a shared plant can be smaller than the sum of every building's peak.",
                  "A diversity of 0.8 means the shared plant is sized at 80% of the summed peaks, which cuts its investment."),
    "contract": ("Contract capacity",
                 "The cooling capacity (kW of refrigeration) a building signs up for with the district cooling system.",
                 "The monthly capacity charge is paid on it whether or not it is used, so over-contracting is expensive."),
    "capacity_charge": ("Capacity charge",
                        "Fixed monthly district-cooling charge: contract capacity × the published rate (HK$ per kW of refrigeration per month).",
                        "Usually the larger part of the district cooling bill; set by EMSD under Cap. 624."),
    "consumption_charge": ("Consumption charge",
                           "Charge per kWh of cooling actually used, at the published EMSD rate.",
                           "It follows the electricity tariff, so it rises and falls with electricity prices."),
    "escalation": ("Real price change",
                   "How much a price rises or falls each year beyond general inflation.",
                   "0% means the price keeps pace with inflation; a positive value makes electricity-heavy options costlier over time."),
    "peak": ("Peak cooling (kW)",
             "The most cooling a building needs at once, on the hottest hour. Here estimated from floor area × an illustrative load per m².",
             "It sizes the equipment and therefore drives the investment and the district cooling capacity charge."),
    "density": ("Cooling density (kW/ha)",
                "Peak cooling per hectare of the area the cluster covers.",
                "Shared cooling pays best where a lot of demand sits close together, so short pipes serve big loads."),
    "pipe": ("Pipe length",
             "Shortest straight-line network joining the building centres (a minimum spanning tree), times a route factor for streets.",
             "A screening proxy for the network cost of a shared plant; real routes are longer and need surveys."),
    "gfa": ("GFA (gross floor area)",
            "Total floor area of a building. Here mostly estimated as footprint × number of storeys, unless a registered value exists.",
            "Cooling demand is scaled from it, so an overestimated GFA (e.g. a large low-rise complex) inflates every result."),
    "tornado": ("Tornado chart",
                "Each input is moved down and up by the same percentage, one at a time, and the change in the result is drawn as a bar.",
                "The longest bars are the inputs worth checking first, because the answer depends on them most."),
    "two_way": ("Two-way table",
                "The result recalculated for every combination of two inputs.",
                "Shows whether a conclusion survives when two uncertain inputs move together."),
    "breakeven": ("Break-even value",
                  "The value of one input at which an option's NPV saving is exactly zero, with everything else unchanged.",
                  "If the break-even is close to today's value, the conclusion is fragile."),
    "distribution": ("Distribution of results",
                     "Each dot is one matched cluster; the box spans the middle half of the clusters and the line inside it is the median.",
                     "A wide box means the answer depends a lot on which buildings you pick; a box above zero means sharing usually pays there."),
}

